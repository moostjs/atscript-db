import { randomUUID } from "node:crypto";
import { describe, it, expect, beforeAll } from "vite-plus/test";

import { DbSpace } from "../table/db-space";
import type { TDbDefaultFn, TDbInsertManyResult } from "../types";

import { MockAdapter, prepareFixtures } from "./test-utils";

// A FROM child's foreign key to a parent key the database generates is not
// known before the parent is written: the child is pre-validated without it
// (a foreign key may be absent there), never with a stand-in of another type
// — a `0` in a string key failed the child's validation, so nested children
// of a parent with a native uuid key could not be inserted at all.

/** The PostgreSQL shape: `uuid` / `increment` generated by the engine. */
class NativeKeysAdapter extends MockAdapter {
  private _next = 0;
  override nativeDefaultFns(): ReadonlySet<TDbDefaultFn> {
    return new Set<TDbDefaultFn>(["uuid", "increment", "now"]);
  }
  override async insertMany(data: Array<Record<string, unknown>>): Promise<TDbInsertManyResult> {
    for (const row of data) {
      row.id ??= this._table.tableName === "nu_parents" ? randomUUID() : ++this._next;
    }
    return super.insertMany(data);
  }
}

let NuParent: any;
let NuKid: any;

beforeAll(async () => {
  await prepareFixtures();
  ({ NuParent, NuKid } = await import("./fixtures/nested-uuid-parent.as"));
});

describe("nested FROM children of a parent with a generated string key", () => {
  it("are inserted and linked to the generated key", async () => {
    const space = new DbSpace(() => new NativeKeysAdapter());
    const { insertedId } = await space
      .getTable(NuParent)
      .insertOne({ label: "p", kids: [{ note: "a" }, { note: "b" }] } as any);
    expect(typeof insertedId).toBe("string");
    const kids = (space.getAdapter(NuKid) as unknown as MockAdapter).store.get("nu_kids");
    expect(kids?.map((k) => [k.note, k.parentId])).toEqual([
      ["a", insertedId],
      ["b", insertedId],
    ]);
  });
});
